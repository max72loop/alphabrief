-- ============================================================
-- AlphaBrief — Suivi des résultats trimestriels de MES sociétés
-- Appliquée par `make db-apply` APRÈS db/schema.sql, le lot 1 et le cycle.
-- ============================================================
--
-- Une ligne = une publication de résultats d'une société détenue, passée ou
-- à venir. Données publiques des sociétés (yfinance), aucun montant de Max.
-- Alimentée par core/providers/trimestres_yf.py à chaque scoring du daemon,
-- lue par Pixel Office (onglet « Résultats », /api/alphabrief/resultats).
--
--   · Clé = ticker NOTÉ (listings.resolve : GOOGL → GOOG), comme ticker_events,
--     societes et les scores : une société, jamais une par cotation.
--   · Une publication À VENIR a bpa_publie NULL ; sa date est souvent une
--     estimation yfinance qui bouge — le provider remplace les lignes futures
--     d'un ticker à chaque synchro plutôt que d'empiler des dates périmées.
--   · `verdict` est calculé en Python (trimestres_yf.verdict), jamais recalculé
--     par l'API : un seul seuil, testé.
--   · `lecture` = 2-3 phrases Haiku écrites UNE fois par publication, gardées.
--
-- Idempotente : rejouable sans effet de bord (vérifié par `make db-reset`,
-- qui rejoue tout deux fois).
-- ============================================================

CREATE TABLE IF NOT EXISTS resultats_trimestriels (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker           TEXT        NOT NULL,
    date_publication DATE        NOT NULL,
    fin_trimestre    DATE,                   -- date de clôture du trimestre publié, si connue
    bpa_attendu      NUMERIC,                -- consensus BPA (EPS estimate)
    bpa_publie       NUMERIC,                -- NULL = pas encore publié
    surprise_pct     NUMERIC,                -- (publié − attendu) / |attendu| × 100
    verdict          TEXT,                   -- 'battu' | 'conforme' | 'rate' | NULL (à venir / inconnu)
    ca               NUMERIC,                -- chiffre d'affaires du trimestre, devise de publication
    ca_attendu       NUMERIC,                -- consensus CA (publication à venir uniquement)
    ca_un_an_avant   NUMERIC,                -- CA du même trimestre un an plus tôt
    resultat_net     NUMERIC,
    devise           TEXT,                   -- devise de publication (financialCurrency)
    lecture          TEXT,                   -- lecture IA, écrite une fois
    lecture_at       TIMESTAMPTZ,
    source           TEXT        NOT NULL DEFAULT 'yfinance',
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Une publication par société et par date : ce qui rend l'upsert possible.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'resultats_trimestriels_ticker_date_key'
    ) THEN
        ALTER TABLE resultats_trimestriels
            ADD CONSTRAINT resultats_trimestriels_ticker_date_key UNIQUE (ticker, date_publication);
    END IF;
END $$;

ALTER TABLE resultats_trimestriels DROP CONSTRAINT IF EXISTS resultats_trimestriels_verdict_check;
ALTER TABLE resultats_trimestriels ADD CONSTRAINT resultats_trimestriels_verdict_check CHECK (
    verdict IS NULL OR verdict IN ('battu', 'conforme', 'rate')
);

-- Un verdict n'existe que sur un résultat publié.
ALTER TABLE resultats_trimestriels DROP CONSTRAINT IF EXISTS resultats_trimestriels_verdict_publie_check;
ALTER TABLE resultats_trimestriels ADD CONSTRAINT resultats_trimestriels_verdict_publie_check CHECK (
    verdict IS NULL OR bpa_publie IS NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_resultats_trimestriels_ticker_date
    ON resultats_trimestriels (ticker, date_publication DESC);
